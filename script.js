const QUESTIONS_PER_GAME = 10;
let questions = [];
let currentIndex = 0;
let score = 0;
let answered = false;

function shuffleArray(arr) {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

const quizScreen    = document.getElementById("quiz-screen");
const resultScreen  = document.getElementById("result-screen");
const questionCount = document.getElementById("question-count");
const progressFill  = document.getElementById("progress-fill");
const questionText  = document.getElementById("question-text");
const choicesEl     = document.getElementById("choices");
const feedbackEl    = document.getElementById("feedback");
const btnNext       = document.getElementById("btn-next");
const scoreText     = document.getElementById("score-text");
const scoreMessage  = document.getElementById("score-message");
const resultIcon    = document.getElementById("result-icon");
const btnRetry      = document.getElementById("btn-retry");

function startQuiz() {
  questions = shuffleArray(ALL_QUESTIONS).slice(0, QUESTIONS_PER_GAME);
  currentIndex = 0;
  score = 0;
  loadQuestion();
}

function loadQuestion() {
  answered = false;
  const q = questions[currentIndex];

  questionCount.textContent = `問題 ${currentIndex + 1} / ${QUESTIONS_PER_GAME}`;
  progressFill.style.width = `${(currentIndex / QUESTIONS_PER_GAME) * 100}%`;
  questionText.textContent = q.question;

  feedbackEl.className = "feedback hidden";
  feedbackEl.textContent = "";
  btnNext.classList.add("hidden");

  choicesEl.innerHTML = "";
  q.choices.forEach((text, i) => {
    const btn = document.createElement("button");
    btn.className = "choice-btn";
    btn.textContent = `${["A", "B", "C", "D"][i]}．${text}`;
    btn.addEventListener("click", () => handleAnswer(i, btn));
    choicesEl.appendChild(btn);
  });
}

function handleAnswer(selectedIndex, selectedBtn) {
  if (answered) return;
  answered = true;

  const q = questions[currentIndex];
  const allBtns = choicesEl.querySelectorAll(".choice-btn");

  allBtns.forEach(btn => btn.disabled = true);
  allBtns[q.correct].classList.add("correct");

  if (selectedIndex === q.correct) {
    score++;
    feedbackEl.className = "feedback correct";
    feedbackEl.textContent = `⭕ 正解！　${q.explanation}`;
  } else {
    selectedBtn.classList.add("wrong");
    feedbackEl.className = "feedback wrong";
    feedbackEl.textContent = `❌ 不正解。正解は「${["A", "B", "C", "D"][q.correct]}．${q.choices[q.correct]}」です。　${q.explanation}`;
  }

  btnNext.classList.remove("hidden");
  btnNext.textContent = currentIndex < QUESTIONS_PER_GAME - 1 ? "次の問題へ →" : "結果を見る";
}

function showResult() {
  quizScreen.classList.add("hidden");
  resultScreen.classList.remove("hidden");

  scoreText.textContent = `${QUESTIONS_PER_GAME}問中 ${score}問 正解`;

  let icon, message;
  if (score === QUESTIONS_PER_GAME) {
    icon = "🏆";
    message = "満点！ガンダムの知識は完璧です！";
  } else if (score >= QUESTIONS_PER_GAME * 0.8) {
    icon = "😄";
    message = "素晴らしい！ガンダムへの造詣が深いですね。";
  } else if (score >= QUESTIONS_PER_GAME * 0.6) {
    icon = "🙂";
    message = "まずまずの結果です。もう一度挑戦してみましょう！";
  } else {
    icon = "📺";
    message = "もう一度ガンダムを見直してから再挑戦しましょう！";
  }

  resultIcon.textContent = icon;
  scoreMessage.textContent = message;
  progressFill.style.width = "100%";
}

btnNext.addEventListener("click", () => {
  currentIndex++;
  if (currentIndex < QUESTIONS_PER_GAME) {
    loadQuestion();
  } else {
    showResult();
  }
});

btnRetry.addEventListener("click", () => {
  resultScreen.classList.add("hidden");
  quizScreen.classList.remove("hidden");
  startQuiz();
});

startQuiz();
